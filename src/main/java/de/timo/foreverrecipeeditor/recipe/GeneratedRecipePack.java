package de.timo.foreverrecipeeditor.recipe;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.mojang.serialization.JsonOps;
import de.timo.foreverrecipeeditor.ForeverRecipeEditor;
import de.timo.foreverrecipeeditor.network.RecipeSnapshot;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Optional;
import net.minecraft.core.HolderLookup;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.PackLocationInfo;
import net.minecraft.server.packs.PackSelectionConfig;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.PathPackResources;
import net.minecraft.server.packs.repository.BuiltInPackSource;
import net.minecraft.server.packs.repository.Pack;
import net.minecraft.server.packs.repository.PackSource;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.crafting.Ingredient;
import net.neoforged.fml.loading.FMLPaths;
import net.neoforged.neoforge.event.AddPackFindersEvent;

public final class GeneratedRecipePack {
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create();
    private static final DateTimeFormatter BACKUP_TIME = DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss-SSS");
    private static final Path ROOT = FMLPaths.CONFIGDIR.get()
            .resolve(ForeverRecipeEditor.MOD_ID)
            .resolve("generated_pack");

    private GeneratedRecipePack() {}

    public static void initialize() {
        try {
            Files.createDirectories(ROOT);
            Path metadata = ROOT.resolve("pack.mcmeta");
            if (Files.notExists(metadata)) {
                Files.writeString(metadata, """
                        {
                          "pack": {
                            "pack_format": 48,
                            "description": "Recipes generated by Forever Recipe Editor"
                          }
                        }
                        """, StandardCharsets.UTF_8);
            }
        } catch (IOException exception) {
            throw new IllegalStateException("Could not create the generated recipe pack", exception);
        }
    }

    public static void addPackFinder(AddPackFindersEvent event) {
        if (event.getPackType() != PackType.SERVER_DATA) {
            return;
        }

        PackLocationInfo info = new PackLocationInfo(
                ForeverRecipeEditor.MOD_ID + "/generated",
                Component.literal("Forever Recipe Editor – Generated Recipes"),
                PackSource.BUILT_IN,
                Optional.empty());
        Pack pack = Pack.readMetaAndCreate(
                info,
                BuiltInPackSource.fromName(location -> new PathPackResources(location, ROOT)),
                PackType.SERVER_DATA,
                new PackSelectionConfig(true, Pack.Position.TOP, false));
        if (pack != null) {
            event.addRepositorySource(consumer -> consumer.accept(pack));
        } else {
            ForeverRecipeEditor.LOGGER.error("Generated recipe pack metadata could not be read from {}", ROOT);
        }
    }

    public static Path root() {
        return ROOT;
    }

    public static void save(RecipeSnapshot.Edit edit, HolderLookup.Provider registries) throws IOException {
        JsonObject json = edit.shaped()
                ? createShaped(edit, registries)
                : createShapeless(edit, registries);
        write(edit.recipeId(), json);
    }

    public static void disable(ResourceLocation recipeId) throws IOException {
        JsonObject condition = new JsonObject();
        condition.addProperty("type", "neoforge:false");
        JsonArray conditions = new JsonArray();
        conditions.add(condition);

        JsonObject json = new JsonObject();
        json.add("neoforge:conditions", conditions);
        write(recipeId, json);
    }

    public static void rename(ResourceLocation oldRecipeId, RecipeSnapshot.Edit edit,
                              HolderLookup.Provider registries) throws IOException {
        if (oldRecipeId.equals(edit.recipeId())) {
            throw new IllegalArgumentException("The new recipe ID must be different");
        }
        save(edit, registries);
        disable(oldRecipeId);
    }

    private static void write(ResourceLocation recipeId, JsonObject json) throws IOException {
        Path recipeFile = ROOT.resolve("data")
                .resolve(recipeId.getNamespace())
                .resolve("recipe")
                .resolve(recipeId.getPath() + ".json")
                .normalize();
        if (!recipeFile.startsWith(ROOT)) {
            throw new IOException("Recipe path escaped the generated pack");
        }

        Files.createDirectories(recipeFile.getParent());
        if (Files.exists(recipeFile)) {
            Path backup = ROOT.resolve("_backups")
                    .resolve(BACKUP_TIME.format(LocalDateTime.now()))
                    .resolve(ROOT.relativize(recipeFile));
            Files.createDirectories(backup.getParent());
            Files.copy(recipeFile, backup, StandardCopyOption.REPLACE_EXISTING);
        }

        Path temporary = recipeFile.resolveSibling(recipeFile.getFileName() + ".tmp");
        Files.writeString(temporary, GSON.toJson(json) + System.lineSeparator(), StandardCharsets.UTF_8);
        try {
            Files.move(temporary, recipeFile, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
        } catch (AtomicMoveNotSupportedException ignored) {
            Files.move(temporary, recipeFile, StandardCopyOption.REPLACE_EXISTING);
        }
    }

    private static JsonObject createShaped(RecipeSnapshot.Edit edit, HolderLookup.Provider registries) {
        int minX = 3;
        int minY = 3;
        int maxX = -1;
        int maxY = -1;
        for (int index = 0; index < 9; index++) {
            if (!edit.ingredients().get(index).isBlank()) {
                int x = index % 3;
                int y = index / 3;
                minX = Math.min(minX, x);
                minY = Math.min(minY, y);
                maxX = Math.max(maxX, x);
                maxY = Math.max(maxY, y);
            }
        }
        if (maxX < 0) {
            throw new IllegalArgumentException("The crafting grid is empty");
        }

        Map<String, Character> symbols = new LinkedHashMap<>();
        JsonObject key = new JsonObject();
        JsonArray pattern = new JsonArray();
        for (int y = minY; y <= maxY; y++) {
            StringBuilder row = new StringBuilder();
            for (int x = minX; x <= maxX; x++) {
                String ingredientJson = edit.ingredients().get(y * 3 + x);
                if (ingredientJson.isBlank()) {
                    row.append(' ');
                    continue;
                }
                char symbol = symbols.computeIfAbsent(ingredientJson, ignored -> (char) ('A' + symbols.size()));
                row.append(symbol);
            }
            pattern.add(row.toString());
        }
        symbols.forEach((ingredientJson, symbol) -> key.add(String.valueOf(symbol), parseIngredient(ingredientJson, registries)));

        JsonObject recipe = base("minecraft:crafting_shaped", edit.result(), registries);
        recipe.add("pattern", pattern);
        recipe.add("key", key);
        recipe.addProperty("show_notification", true);
        return recipe;
    }

    private static JsonObject createShapeless(RecipeSnapshot.Edit edit, HolderLookup.Provider registries) {
        JsonArray ingredients = new JsonArray();
        for (String ingredientJson : edit.ingredients()) {
            if (!ingredientJson.isBlank()) {
                ingredients.add(parseIngredient(ingredientJson, registries));
            }
        }
        if (ingredients.isEmpty()) {
            throw new IllegalArgumentException("The crafting grid is empty");
        }
        JsonObject recipe = base("minecraft:crafting_shapeless", edit.result(), registries);
        recipe.add("ingredients", ingredients);
        return recipe;
    }

    private static JsonObject base(String type, ItemStack result, HolderLookup.Provider registries) {
        if (result.isEmpty()) {
            throw new IllegalArgumentException("The result slot is empty");
        }
        JsonObject recipe = new JsonObject();
        recipe.addProperty("type", type);
        recipe.addProperty("category", "misc");
        JsonElement encodedResult = ItemStack.STRICT_CODEC
                .encodeStart(registries.createSerializationContext(JsonOps.INSTANCE), result)
                .getOrThrow(error -> new IllegalArgumentException("Invalid result: " + error));
        recipe.add("result", encodedResult);
        return recipe;
    }

    private static JsonElement parseIngredient(String json, HolderLookup.Provider registries) {
        JsonElement element = JsonParser.parseString(json);
        Ingredient.CODEC.parse(registries.createSerializationContext(JsonOps.INSTANCE), element)
                .getOrThrow(error -> new IllegalArgumentException("Invalid ingredient: " + error));
        return element;
    }
}
